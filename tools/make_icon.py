"""Generates the fyewebcam app icons: a flat lens ring with "fwc" in the middle.

Writes the Android adaptive icon foreground (vector), the Windows app.ico and docs/icon.svg.
Needs Pillow and fontTools, plus the Inter Bold font (fonts-inter). Run from the repo root:
    python3 tools/make_icon.py
"""

import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/opentype/inter/Inter-Bold.otf"
TEXT = "fwc"
ACCENT = "#2DD4BF"
DARK = "#0F1115"

# Geometry in a 108-unit square (the Android adaptive icon canvas; 66 units in the middle are safe).
SIZE = 108
CENTER = SIZE / 2
RING_OUTER = 31
RING_INNER = 26
TEXT_WIDTH = 34


def text_path():
    """'fwc' as an SVG path, centred on the canvas, TEXT_WIDTH units wide."""
    font = TTFont(FONT)
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    names = [cmap[ord(c)] for c in TEXT]
    advance = sum(glyphs[n].width for n in names)
    scale = TEXT_WIDTH / advance
    os2 = font["OS/2"]
    x_height = os2.sxHeight * scale
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    x = CENTER - TEXT_WIDTH / 2
    # Centre the lowercase x-height band vertically (the f ascender sits above it).
    baseline = CENTER + x_height / 2
    for n in names:
        glyphs[n].draw(TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
        x += glyphs[n].width * scale
    return pen.getCommands()


def ring_path():
    def circle(r):
        return (f"M{CENTER - r},{CENTER}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0z")
    return circle(RING_OUTER) + circle(RING_INNER)


def write_android(root, letters, ring):
    xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icon.py: lens ring with "fwc". -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#FF{ACCENT[1:]}" android:fillType="evenOdd"
        android:pathData="{ring}" />
    <path android:fillColor="#FF{ACCENT[1:]}"
        android:pathData="{letters}" />
</vector>
"""
    (root / "android/app/src/main/res/drawable/ic_launcher_foreground.xml").write_text(xml)


def write_svg(root, letters, ring):
    # Standalone icon: a dark disc behind the ring.
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="{CENTER - RING_OUTER - 2} {CENTER - RING_OUTER - 2} {2 * RING_OUTER + 4} {2 * RING_OUTER + 4}">
  <circle cx="{CENTER}" cy="{CENTER}" r="{RING_OUTER + 2}" fill="{DARK}"/>
  <path fill="{ACCENT}" fill-rule="evenodd" d="{ring}"/>
  <path fill="{ACCENT}" d="{letters}"/>
</svg>
"""
    (root / "docs/icon.svg").write_text(svg)


def render(px):
    """The Windows icon at px x px: a dark disc, the ring, and 'fwc', supersampled for smooth edges."""
    ss = 8
    big = px * ss
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    # Map the ring's bounding box (plus a 2-unit margin) to the full image.
    unit = big / (2 * RING_OUTER + 4)
    c = big / 2
    d.ellipse([0, 0, big - 1, big - 1], fill=DARK)
    ro, ri = RING_OUTER * unit, RING_INNER * unit
    d.ellipse([c - ro, c - ro, c + ro, c + ro], fill=ACCENT)
    d.ellipse([c - ri, c - ri, c + ri, c + ri], fill=DARK)
    if px >= 24:
        font_px = 10
        while True:
            f = ImageFont.truetype(FONT, font_px)
            if d.textlength(TEXT, font=f) >= TEXT_WIDTH * unit:
                break
            font_px += 2
        d.text((c, c), TEXT, font=f, fill=ACCENT, anchor="mm")
    else:
        # Too small for letters: a filled lens centre instead.
        r = RING_INNER * unit * 0.45
        d.ellipse([c - r, c - r, c + r, c + r], fill=ACCENT)
    return img.resize((px, px), Image.LANCZOS)


def write_ico(root):
    sizes = [16, 24, 32, 48, 64, 128, 256]
    images = [render(s) for s in sizes]
    images[-1].save(root / "windows/src/app.ico", sizes=[(s, s) for s in sizes], append_images=images[:-1])
    images[-1].save(root / "docs/icon.png")


def main():
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(".")
    letters, ring = text_path(), ring_path()
    write_android(root, letters, ring)
    write_svg(root, letters, ring)
    write_ico(root)


if __name__ == "__main__":
    main()
